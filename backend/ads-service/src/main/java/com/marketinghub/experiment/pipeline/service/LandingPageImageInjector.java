package com.marketinghub.experiment.pipeline.service;

import com.fasterxml.jackson.core.JsonProcessingException;
import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.databind.node.ObjectNode;
import com.fasterxml.jackson.databind.node.ArrayNode;
import com.marketinghub.experiment.frameworkimage.FrameworkImageGenerationJob;
import com.marketinghub.repository.jpa.experiment.frameworkimage.FrameworkImageGenerationJobRepository;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Objects;
import java.util.Set;
import java.util.function.Predicate;
import org.jsoup.Jsoup;
import org.jsoup.nodes.Document;
import org.jsoup.nodes.Element;
import org.jsoup.parser.Parser;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.stereotype.Component;
import org.springframework.util.CollectionUtils;
import org.springframework.util.StringUtils;

/**
 * Enriches landing page HTML payloads with the image URLs generated by the framework-image pipeline.
 */
@Component
public class LandingPageImageInjector {

    private static final Logger log = LoggerFactory.getLogger(LandingPageImageInjector.class);

    private final FrameworkImageGenerationJobRepository jobRepository;
    private final ObjectMapper objectMapper;

    public LandingPageImageInjector(FrameworkImageGenerationJobRepository jobRepository,
                                    ObjectMapper objectMapper) {
        this.jobRepository = jobRepository;
        this.objectMapper = objectMapper;
    }

    public String injectImages(Long experimentId, String landingPagePayload) {
        if (experimentId == null || !StringUtils.hasText(landingPagePayload)) {
            return landingPagePayload;
        }
        Map<String, String> sectionImages = resolveSectionImages(experimentId);
        if (CollectionUtils.isEmpty(sectionImages)) {
            return landingPagePayload;
        }

        String enrichedJson = tryInjectInsideJsonPayload(landingPagePayload, sectionImages);
        if (enrichedJson != null) {
            return enrichedJson;
        }

        return updateHtmlDocument(landingPagePayload, sectionImages);
    }

    public String injectImageUrlsIntoPlanning(Long experimentId, String rawPlanningPayload) {
        if (experimentId == null || !StringUtils.hasText(rawPlanningPayload)) {
            return rawPlanningPayload;
        }
        Map<String, String> sectionImages = resolveSectionImages(experimentId);
        if (CollectionUtils.isEmpty(sectionImages)) {
            return rawPlanningPayload;
        }
        try {
            JsonNode root = objectMapper.readTree(rawPlanningPayload);
            if (!(root instanceof ObjectNode rootObject)) {
                return rawPlanningPayload;
            }
            ObjectNode planningNode = resolvePlanningObject(rootObject);
            if (planningNode == null) {
                return rawPlanningPayload;
            }
            JsonNode imagesNode = planningNode.path("images");
            if (!(imagesNode instanceof ArrayNode imagesArray)) {
                return rawPlanningPayload;
            }
            boolean changed = false;
            for (JsonNode imageNode : imagesArray) {
                if (!(imageNode instanceof ObjectNode imageObject)) {
                    continue;
                }
                String sectionId = imageObject.path("sectionId").asText(null);
                String url = StringUtils.hasText(sectionId) ? sectionImages.get(sectionId.trim().toLowerCase()) : null;
                if (!StringUtils.hasText(url)) {
                    continue;
                }
                if (!url.equals(imageObject.path("imageUrl").asText(null))) {
                    imageObject.put("imageUrl", url);
                    changed = true;
                }
            }
            return changed ? objectMapper.writeValueAsString(rootObject) : rawPlanningPayload;
        } catch (JsonProcessingException ex) {
            return rawPlanningPayload;
        }
    }

    private ObjectNode resolvePlanningObject(ObjectNode rootObject) {
        JsonNode direct = rootObject.path("landingPageImagePlanning");
        if (direct instanceof ObjectNode objectNode) {
            return objectNode;
        }
        JsonNode imagePlan = rootObject.path("imagePlan");
        if (imagePlan instanceof ObjectNode objectNode) {
            return objectNode;
        }
        JsonNode artifactContent = rootObject.path("artifact").path("content");
        if (artifactContent instanceof ObjectNode objectNode) {
            return objectNode;
        }
        return rootObject;
    }

    private Map<String, String> resolveSectionImages(Long experimentId) {
        List<FrameworkImageGenerationJob> jobs = jobRepository.findByExperimentIdOrderByCreatedAtDesc(experimentId);
        if (jobs == null || jobs.isEmpty()) {
            return Map.of();
        }
        Map<String, String> imagesBySection = new LinkedHashMap<>();
        for (FrameworkImageGenerationJob job : jobs) {
            if (job == null || !StringUtils.hasText(job.getPlanningItemKey())) {
                continue;
            }
            if (imagesBySection.containsKey(job.getPlanningItemKey())) {
                continue;
            }
            String url = firstNonBlank(job.getWebUrl(), job.getSourceUrl());
            if (!StringUtils.hasText(url)) {
                continue;
            }
            imagesBySection.put(job.getPlanningItemKey(), url.trim());
        }
        return imagesBySection;
    }

    private String firstNonBlank(String primary, String fallback) {
        if (StringUtils.hasText(primary)) {
            return primary;
        }
        if (StringUtils.hasText(fallback)) {
            return fallback;
        }
        return null;
    }

    private String tryInjectInsideJsonPayload(String payload, Map<String, String> sectionImages) {
        try {
            JsonNode root = objectMapper.readTree(payload);
            if (!(root instanceof ObjectNode objectNode)) {
                return null;
            }
            JsonNode landingNode = objectNode.get("landingPageHtml");
            if (!(landingNode instanceof ObjectNode landingObject)) {
                return null;
            }
            JsonNode htmlNode = landingObject.get("htmlDocument");
            if (htmlNode == null || !htmlNode.isTextual()) {
                return null;
            }
            String originalHtml = htmlNode.asText();
            String enrichedHtml = updateHtmlDocument(originalHtml, sectionImages);
            if (Objects.equals(originalHtml, enrichedHtml)) {
                return payload;
            }
            landingObject.put("htmlDocument", enrichedHtml);
            return objectMapper.writeValueAsString(objectNode);
        } catch (JsonProcessingException ex) {
            return null;
        }
    }

    private String updateHtmlDocument(String html, Map<String, String> sectionImages) {
        if (!StringUtils.hasText(html)) {
            return html;
        }
        try {
            Document document = Jsoup.parse(html, "", Parser.htmlParser());
            document.outputSettings().prettyPrint(false);
            List<ImageCandidate> availableImages = sectionImages.entrySet().stream()
                    .map(entry -> new ImageCandidate(normalizeMatchValue(entry.getKey()), entry.getValue()))
                    .filter(candidate -> StringUtils.hasText(candidate.url()))
                    .toList();
            if (availableImages.isEmpty()) {
                return html;
            }

            Set<Integer> consumedIndexes = new HashSet<>();
            boolean changed = false;
            for (Element imageElement : document.select("img")) {
                ImageCandidate matched = consumeFirstAvailable(availableImages, consumedIndexes,
                        candidate -> collectMatchCandidates(imageElement).stream()
                                .anyMatch(value -> value.equals(candidate.matchKey())
                                        || value.contains(candidate.matchKey())));

                if (matched == null && shouldFallbackToNextImage(imageElement)) {
                    matched = consumeFirstAvailable(availableImages, consumedIndexes, candidate -> true);
                }

                if (matched != null && !Objects.equals(imageElement.attr("src"), matched.url())) {
                    imageElement.attr("src", matched.url());
                    changed = true;
                }
            }
            return changed ? document.outerHtml() : html;
        } catch (Exception ex) {
            log.warn("Failed to inject framework images into landing page HTML", ex);
            return html;
        }
    }

    private List<String> collectMatchCandidates(Element imageElement) {
        List<String> candidates = new ArrayList<>();
        addCandidate(candidates, imageElement.attr("data-planning-item-key"));
        addCandidate(candidates, imageElement.attr("data-section-id"));
        addCandidate(candidates, imageElement.attr("data-section-name"));
        addCandidate(candidates, imageElement.attr("data-image-key"));
        addCandidate(candidates, imageElement.attr("data-image-section-id"));
        addCandidate(candidates, imageElement.attr("data-image-binding-key"));
        addCandidate(candidates, imageElement.attr("data-image-role"));
        addCandidate(candidates, imageElement.attr("data-conversion-role"));
        addCandidate(candidates, imageElement.id());
        addCandidate(candidates, imageElement.attr("alt"));
        addCandidate(candidates, imageElement.className());
        Element closestSection = imageElement.closest("section");
        if (closestSection != null) {
            addCandidate(candidates, closestSection.id());
            addCandidate(candidates, closestSection.attr("data-section-id"));
            addCandidate(candidates, closestSection.attr("data-planning-item-key"));
            addCandidate(candidates, closestSection.className());
        }
        return candidates;
    }

    private void addCandidate(List<String> candidates, String rawValue) {
        String normalized = normalizeMatchValue(rawValue);
        if (StringUtils.hasText(normalized)) {
            candidates.add(normalized);
        }
    }

    private String normalizeMatchValue(String rawValue) {
        return rawValue == null ? "" : rawValue.trim().toLowerCase();
    }

    private boolean shouldFallbackToNextImage(Element imageElement) {
        String src = normalizeMatchValue(imageElement.attr("src"));
        return !StringUtils.hasText(src)
                || src.startsWith("about:blank")
                || src.contains("placehold.co")
                || src.contains("placeholder");
    }

    private ImageCandidate consumeFirstAvailable(List<ImageCandidate> availableImages,
                                                 Set<Integer> consumedIndexes,
                                                 Predicate<ImageCandidate> matcher) {
        for (int index = 0; index < availableImages.size(); index++) {
            if (consumedIndexes.contains(index)) {
                continue;
            }
            ImageCandidate candidate = availableImages.get(index);
            if (!matcher.test(candidate)) {
                continue;
            }
            consumedIndexes.add(index);
            return candidate;
        }
        return null;
    }

    private record ImageCandidate(String matchKey, String url) {
    }
}
