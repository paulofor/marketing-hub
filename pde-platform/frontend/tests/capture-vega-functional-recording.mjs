import { chromium, devices } from '@playwright/test';
import { mkdir, writeFile, readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import path from 'node:path';

// Registra o software real em banco sintético local; recusa hosts publicados e não usa APIs de geração.
const base = process.env.VEGA_CAPTURE_BASE || 'http://127.0.0.1:57188';
if (!['127.0.0.1', 'localhost'].includes(new URL(base).hostname)) throw new Error('A captura aceita somente a sandbox local.');
const out = path.resolve(process.env.VEGA_CAPTURE_OUTPUT || '../../.codex/vega-resume/functional-recording');
await mkdir(out, { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_BIN || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] });
const context = await browser.newContext({ ...devices['iPhone 15 Pro'], recordVideo: { dir: out, size: { width: 540, height: 1170 } } });
const api = '/api/pde/vega/style/v1';
const created = await context.request.post(base + api + '/internal/sessions', { headers: { 'X-PDE-Internal-Token': 'vega-local-internal-only' }, data: { cycleId: 91003, prototypeVersion: 'musa-pde-entry-v17-continuidade-clara' } });
if (!created.ok()) throw new Error('A sessão local não foi criada: ' + created.status());
const session = await created.json();
await context.addCookies([{ name: 'vega-style-session', value: session.sessionToken, domain: new URL(base).hostname, path: api, httpOnly: true, sameSite: 'Strict' }]);
const page = await context.newPage();

const video = page.video();
const start = performance.now();
const actions = [];
const mark = (action) => actions.push({ action, seconds: (performance.now() - start) / 1000 });
await page.goto(base + '/experiences/musa-pde-entry-v17-continuidade-clara/agent-validation');
await page.getByRole('button', { name: 'Experimentar com minhas roupas', exact: true }).click();
await page.getByLabel('Onde você vai usar?').fill('almoço');
await page.getByLabel('Quais roupas você já tem em mente?').fill('camisa, lenço e bolsa; posso usar o lenço no pescoço ou na alça');
await page.getByLabel('O que você quer sentir').selectOption('Cor e criatividade');
await page.waitForTimeout(1500);
mark('INPUT_SUBMITTED');
await page.getByRole('button', { name: 'Ver minha orientação', exact: true }).click();
const card = page.getByRole('article', { name: 'Sua orientação pronta' });
await card.waitFor({ timeout: 10000 }).catch(async error => { await page.screenshot({ path: path.join(out, 'failure.png'), fullPage: true }); await writeFile(path.join(out, 'failure.txt'), await page.locator('body').innerText()); await context.close(); await browser.close(); throw error; });
if (!(await card.innerText()).includes('alça da bolsa')) throw new Error('A orientação funcional esperada não apareceu.');
await card.scrollIntoViewIfNeeded();
mark('RESULT_VISIBLE');
await page.waitForTimeout(2500);
await page.getByRole('button', { name: 'Salvar e concluir este dia', exact: true }).scrollIntoViewIfNeeded();
await page.waitForTimeout(1000);
mark('SAVE_AND_COMPLETE');
await page.getByRole('button', { name: 'Salvar e concluir este dia', exact: true }).click();
await page.getByRole('heading', { name: 'Sua jornada está guardada' }).waitFor();
await page.waitForTimeout(2000);
await page.reload();
await page.getByRole('button', { name: /Dia 1$/ }).click();
await card.waitFor();
await card.scrollIntoViewIfNeeded();
if (!(await card.innerText()).includes('alça da bolsa')) throw new Error('A orientação salva não foi recuperada.');
mark('REOPEN_SAVED');
await page.waitForTimeout(3000);
const reportResponse = await context.request.get(base + api + '/internal/report', { headers: { 'X-PDE-Internal-Token': 'vega-local-internal-only', 'X-Vega-Style-Session': session.sessionToken } });
const report = await reportResponse.json();
if (report.trafficClass !== 'AGENT_VALIDATION' || report.sideEffects.paymentEnabled !== false || Object.keys(report.operations).length !== 1) throw new Error('O relatório não confirmou a segregação ou a operação única.');
await page.screenshot({ path: path.join(out, 'saved-reopened.png') });
await context.close();
await browser.close();
const source = await video.path();
const mp4 = path.join(out, 'functional-recording.mp4');
execFileSync('ffmpeg', ['-v', 'error', '-y', '-i', source, '-an', '-c:v', 'libx264', '-threads', '2', '-preset', 'slow', '-crf', '23', '-pix_fmt', 'yuv420p', '-movflags', '+faststart', mp4]);
const probe = JSON.parse(execFileSync('ffprobe', ['-v', 'error', '-show_format', '-show_streams', '-of', 'json', mp4], { encoding: 'utf8' }));
const stream = probe.streams.find(x => x.codec_type === 'video');
const files = ['src/MusaPersonalStyleApp.tsx', '../../backend/ads-service/src/main/java/com/marketinghub/pde/vega/style/v1/service/VegaStyleService.java'];
const sourceFiles = [];
for (const file of files) sourceFiles.push({ path: file, sha256: createHash('sha256').update(await readFile(file)).digest('hex') });
const manifest = { contractVersion: 'PRODUCT_FUNCTIONAL_RECORDING_V1', productId: 4, fixtureProductId: 91004, fixtureCycleId: 91003, sourcePrototypeVersion: 'musa-pde-entry-v17-continuidade-clara', captureEnvironment: 'LOCAL_SANDBOX', trafficClass: 'AGENT_VALIDATION', syntheticData: true, commercialEvidenceClaimed: false, qualityApproved: false, capturedAt: new Date().toISOString(), sourceFingerprint: createHash('sha256').update(JSON.stringify(sourceFiles)).digest('hex'), sourceFiles, sha256: createHash('sha256').update(await readFile(mp4)).digest('hex'), durationSeconds: Number(probe.format.duration), width: stream.width, height: stream.height, videoCodec: stream.codec_name, audioStreams: probe.streams.filter(s => s.codec_type === 'audio').length, actions, verification: { realBackend: true, mysql57: true, singleContextualOperation: true, savedAndReopened: true, externalProviderCalls: 0, paymentEnabled: false } };
if (actions.at(-1).seconds >= manifest.durationSeconds) throw new Error('Relógio da gravação inconsistente.');
await writeFile(path.join(out, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
console.log(JSON.stringify({ mp4, durationSeconds: manifest.durationSeconds, sha256: manifest.sha256, actions: actions.length, providerCalls: 0 }));
